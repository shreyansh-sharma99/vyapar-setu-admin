// Builds src/styles/coreui-base.css: CoreUI's stylesheet without its utility classes.
//
// CoreUI utilities (.p-4, .mb-3, .gap-5, .order-last, .shadow, .rounded …) are all
// `!important` and share names with Tailwind classes, so they silently override Tailwind
// (an !important rule wins over any cascade layer). The app only needs CoreUI's component
// styles (CToast, CCard, grid) and reboot, which never use !important.
//
// Run after upgrading @coreui/coreui:  node scripts/strip-coreui-utilities.mjs

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import postcss from 'postcss';

const require = createRequire(import.meta.url);
const source = require.resolve('@coreui/coreui/dist/css/coreui.min.css');
const target = new URL('../src/styles/coreui-base.css', import.meta.url);

const root = postcss.parse(readFileSync(source, 'utf8'));
let removed = 0;

// Any rule with an !important declaration goes: that is every utility (.p-4, .text-success …)
// plus a few navbar / offcanvas helpers the app doesn't use. Component styles never use it.
root.walkRules((rule) => {
  if (rule.nodes.some((n) => n.type === 'decl' && n.important)) {
    rule.remove();
    removed += 1;
  }
});
// Drop @media / @supports blocks left empty by the removal.
root.walkAtRules((at) => {
  if (at.nodes && at.nodes.length === 0) at.remove();
});
root.walkComments((c) => c.remove());

mkdirSync(new URL('.', target), { recursive: true });
writeFileSync(
  target,
  `/* Generated by scripts/strip-coreui-utilities.mjs from @coreui/coreui — do not edit. */\n${root.toString()}\n`,
);
console.log(`coreui-base.css written, ${removed} utility rules removed`);
