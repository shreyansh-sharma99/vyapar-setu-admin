// Fetched once per page load and shared by both audit screens
let sourcesCache = null;

/** Activity options from GET /inventory/sources, falling back to SOURCE_OPTIONS. */
export const useStockSources = () => {
  const [sources, setSources] = useState(sourcesCache || SOURCE_OPTIONS);
  useEffect(() => {
    if (sourcesCache) return undefined;
    let alive = true;
    getStockSourcesApi()
      .then((res) => {
        if (Array.isArray(res?.data) && res.data.length) {
          sourcesCache = res.data;
          if (alive) setSources(res.data);
        }
      })
      .catch(() => {
        /* keep the fallback list */
      });
    return () => {
      alive = false;
    };
  }, []);
  return sources;
};

export const formatDateTime = (dateStr) => {
  if (!dateStr) return '-';
  return new Date(dateStr).toLocaleString('en-IN', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: true,
  });
};

export const getActorName = (log) => {
  if (log.actorId && typeof log.actorId === 'object' && log.actorId.name && log.actorId.name !== 'Admin') {
    return log.actorId.name;
  }
  if (log.actorName && log.actorName !== 'Admin') return log.actorName;
  return log.actorId?.name || log.actorName || 'User';
};

/**
 * Converts filter state into API params. Dates are sent as exact day
 * boundaries in the user's timezone.
 */
export const buildAuditParams = ({ storeId, source, bucket, dateRange, search, productId }) => ({
  productId: productId || undefined,
  storeId: storeId || undefined,
  source: source || undefined,
  bucket: bucket || undefined,
  startDate: dateRange?.[0] ? dateRange[0].startOf('day').toISOString() : undefined,
  endDate: dateRange?.[1] ? dateRange[1].endOf('day').toISOString() : undefined,
  search: search?.trim() || undefined,
});

/* ─── CSV export ────────────────────────────────────────────────────────── */

/**
 * Downloads the full CSV (all records matching params) generated by the backend.
 * Returns { exporting, exportCsv(params, fileNamePrefix) }.
 */
export const useAuditCsvExport = (onError) => {
  const [exporting, setExporting] = useState(false);

  const exportCsv = async (params, fileNamePrefix = 'Stock_Audit_Report') => {
    setExporting(true);
    try {
      const blob = await exportAuditReportCsvApi(params);
      const url = window.URL.createObjectURL(new Blob([blob], { type: 'text/csv;charset=utf-8' }));
      const link = document.createElement('a');
      link.href = url;
      link.setAttribute('download', `${fileNamePrefix}_${new Date().toISOString().split('T')[0]}.csv`);
      document.body.appendChild(link);
      link.click();
      link.remove();
      window.URL.revokeObjectURL(url);
    } catch (err) {
      console.error('CSV export failed:', err);
      onError?.('Failed to export CSV. Please try again.');
    } finally {
      setExporting(false);
    }
  };

  return { exporting, exportCsv };
};
